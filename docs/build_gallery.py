#!/usr/bin/env python3
"""Generate ``docs/analysis/figures.qmd`` from the figures in ``test/output_figures/gallery``.

WHY THIS IS GENERATED. Every figure is written under its title, with a ``.txt``
beside it holding the title, the figure's own numbers and the description (see
``falconage.plot.save_figure``). Writing that text a second time in a
documentation page would put two copies of one sentence in the repository, and
the copy on the website would be the one nobody regenerates. So the page is
assembled from the PNGs and their ``.txt`` files, and the caption on the site
and the legend text shipped with the figure cannot disagree.

The tracked copy of each figure stays where ``test/run_all.py`` writes it, under
``test/output_figures/gallery/``. Quarto will not include a resource from
outside its project directory, so this also stages a copy into
``docs/figures/gallery/`` -- derived, gitignored, and regenerated here rather
than maintained.

Usage
-----
    python docs/build_gallery.py           # write docs/analysis/figures.qmd
    python docs/build_gallery.py --check   # fail if stale (for CI)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
GALLERY = ROOT / "test" / "output_figures" / "gallery"
TARGET = HERE / "analysis" / "figures.qmd"

BANNER = ("<!-- GENERATED by docs/build_gallery.py from test/output_figures/gallery.\n"
          "     Edit that script, colorscheme.yaml, or regenerate the figures. -->")

# Figures grouped the way somebody reads them, rather than alphabetically.
# A name absent from every group still appears, under "Other" -- silently
# dropping a figure is how the gallery stops being a gallery.
GROUPS = [
    ("Start here", ["clock_coverage_manhattan", "clock_atlas"],
     "Where every clock's CpGs sit on the genome and which ones the array "
     "carries, then the question everyone actually has: which of these "
     "algorithms detects anything."),
    ("Is the clock calibrated", ["ba_vs_ca", "bland_altman", "calibration"],
     "Before any biology: does the prediction track chronological age, and "
     "where does it drift."),
    ("Age acceleration", ["acceleration_by_group", "acceleration_density",
                          "acceleration_heatmap", "forest"],
     "The residual after age is removed, by group and across studies."),
    ("Outcomes", ["kaplan_meier", "volcano"],
     "Whether acceleration predicts anything that happens to a person."),
    ("How the clocks relate", ["clock_corr", "clock_chord", "clock_radar",
                               "clock_pca"],
     "Twenty clocks are not twenty measurements. These show how much they "
     "share -- of their features, and of their answers."),
    ("Benchmarking", ["benchmark_bars", "benchmark_error_bias",
                      "benchmark_heatmap"],
     "AA1 and AA2 against the ComputAgeBench conditions, and the "
     "error-versus-bias tradeoff that decides the ranking."),
    ("Data quality", ["coverage_bar", "missingness", "beta_density",
                      "platform_comparison", "study_comparison"],
     "Drawn before the results, because a coverage problem invalidates "
     "everything after it."),
]

HEAD = """---
title: "Figure gallery"
subtitle: "Every figure the package draws, on real data, with what each one is for"
aliases:
  - ../gallery.html
---

{banner}

Each of these is produced by `test/run_all.py` against the public test corpus
and copied into `test/output_figures/gallery/`. They are regenerated from the
code, so a figure here is what the current version actually draws -- not a
screenshot taken once.

The figures carry no title or caption on the canvas, only axes and legend, so
they drop into a manuscript or a panel layout as they are. Each PNG is named
after its title, and a `.txt` of the same name beside it holds the title, the
figure's own numbers and the description; the caption under each image here is
read from that file. The same file's `ui` block sets the colours and fonts of
both HTML reports and of this site, so a figure, a report and a page of the
documentation share one palette: Okabe-Ito for data, because group membership
is carried by hue alone and has to survive colour-vision deficiency, and the
logo orange, in a darker shade where it is text, only for links and controls.

::: {{.callout-note}}
## Reproducing these

```bash
docker run --rm -v "$PWD:/work" -w /work falconage:1.0.0-cpu \\
  python test/run_all.py
```

Which dataset each figure comes from, and why that one was chosen, is recorded
in [SOURCES.md]({repo}/blob/main/test/output_figures/gallery/SOURCES.md).
:::

"""


def descriptions() -> dict[str, dict]:
    sys.path.insert(0, str(ROOT / "python" / "src"))
    from falconage.plot import spec

    return spec.load()["plots"]


def stage_images() -> int:
    """Copy the PNGs under docs/, because Quarto cannot reach above its root.

    The figures live in `test/output_figures/gallery/` and are tracked there --
    that is the copy a reader of the repository sees, and the one a diff
    reports when somebody edits the colour scheme. Quarto will not include a
    resource from outside its project directory, so the site needs its own
    copy. It is derived, so it is gitignored; only the original is tracked.
    """
    import shutil

    dest = HERE / "figures" / "gallery"
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True, exist_ok=True)
    n = 0
    for png in sorted(GALLERY.glob("*.png")):
        shutil.copyfile(png, dest / png.name)
        if png.with_suffix(".txt").is_file():
            shutil.copyfile(png.with_suffix(".txt"), dest / f"{png.stem}.txt")
        n += 1
    return n


def _stems() -> dict[str, str]:
    """colorscheme.yaml plot key to the file stem its figure is written under."""
    sys.path.insert(0, str(ROOT / "python" / "src"))
    from falconage.plot._common import _slug

    return {k: _slug(v["title"]) for k, v in descriptions().items()}


def render() -> str:
    stems = _stems()
    key_of = {v: k for k, v in stems.items()}
    present = {p.stem for p in GALLERY.glob("*.png")}

    out = [HEAD.format(banner=BANNER,
                       repo="https://github.com/bhagesh-h/FALCONAge")]
    shown: set[str] = set()

    for title, names, blurb in GROUPS:
        here = [stems[n] for n in names if stems.get(n) in present]
        if not here:
            continue
        out.append(f"## {title}\n")
        out.append(blurb + "\n")
        for stem in here:
            shown.add(stem)
            out.append(_figure(stem, key_of.get(stem)))

    rest = sorted(present - shown)
    if rest:
        out.append("## Other\n")
        out.append("Figures not yet placed in a section above.\n")
        for stem in rest:
            out.append(_figure(stem, key_of.get(stem)))

    # No horizontal rule before this. The heading structure already separates
    # the sections, and a rule between them is decoration that reads as filler.
    out.append(f"\n## In total\n\n{len(present)} figures. "
               "Every one is also written per dataset under "
               "`test/output_figures/<group>/<dataset>/` when the full corpus "
               "run is executed; the gallery keeps one representative of each "
               "type so a reader does not have to fetch 586 MB to see them.\n")
    return "\n".join(out)


def _caption(stem: str) -> dict[str, str]:
    from falconage.plot._common import read_caption

    return read_caption(GALLERY / f"{stem}.png")


def _figure(stem: str, key: str | None) -> str:
    t = _caption(stem)
    title = t["title"] or stem.replace("_", " ").capitalize()
    rel = f"../figures/gallery/{stem}.png"

    block = [f"### {title}\n", f"![{title}]({rel})\n"]
    if t["subtitle"]:
        block.append(f"*{t['subtitle']}.*\n")
    if t["description"]:
        block.append(f"{t['description']}\n")
    files = f"`{stem}.png` with `{stem}.txt`"
    block.append(f"`plot.{key}()` in Python; written as {files}.\n" if key
                 else f"Written as {files}.\n")
    return "\n".join(block)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if docs/analysis/figures.qmd is out of date")
    args = ap.parse_args(argv)

    if not GALLERY.exists():
        print(f"{GALLERY.relative_to(ROOT)} does not exist; run "
              "test/run_all.py first")
        return 1

    text = render()
    current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None

    if args.check:
        if current != text:
            print(f"{TARGET.relative_to(ROOT)} is stale; run docs/build_gallery.py")
            return 1
        print(f"{TARGET.relative_to(ROOT)} is current")
        return 0

    staged = stage_images()
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)} and staged {staged} figure(s) "
          "into docs/figures/gallery")
    return 0


if __name__ == "__main__":
    sys.exit(main())
